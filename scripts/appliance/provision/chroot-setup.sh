#!/bin/sh
# Runs inside the Alpine image chroot (via alpine-make-vm-image --script-chroot).
# Expects published app bits at /mnt/publish/{api,web} (bound from build host).
# BusyBox ash: no pipefail; check pipeline exits explicitly.
set -eu

einfo() { printf '\n\033[1;36m> %s\033[0m\n' "$*" >&2; }
ewarn() { printf '\n\033[1;33mWARNING:\033[0m %s\n' "$*" >&2; }
edie() { printf '\n\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# Build-time defaults (exported by build-appliance.sh into /mnt/build.env)
if [ -f /mnt/build.env ]; then
	# shellcheck disable=SC1091
	. /mnt/build.env
fi

# Do not rely on $HOSTNAME alone — some environments pre-set it oddly.
APP_HOSTNAME="${HOSTNAME:-schnapp}"
ROOT_PASSWORD="${ROOT_PASSWORD:-schnapp}"
DB_NAME="${DB_NAME:-schnapp}"
DB_USER="${DB_USER:-schnapp}"
DB_PASSWORD="${DB_PASSWORD:-schnapp}"
DATA_MOUNTPOINT="${DATA_MOUNTPOINT:-/opt/schnapp/data}"
DATA_DISK_LABEL="${DATA_DISK_LABEL:-schnapp-data}"
PGDATA="${PGDATA:-/opt/schnapp/data/postgresql}"
BLOB_MOUNTPOINT="${BLOB_MOUNTPOINT:-/opt/schnapp/data/blobs}"
BLOB_NFS="${BLOB_NFS:-}"
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@example.com}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-change-me}"
API_PORT="${API_PORT:-5080}"
WEB_PORT="${WEB_PORT:-80}"
HTTPS_PORT="${HTTPS_PORT:-443}"
HTTPS_ENABLE="${HTTPS_ENABLE:-1}"
API_BIND="${API_BIND:-0.0.0.0}"
WEB_BIND="${WEB_BIND:-0.0.0.0}"
BACKUP_DIR="${BACKUP_DIR:-/opt/schnapp/data/blobs/_appliance/db}"

einfo "hostname → ${APP_HOSTNAME}"
# Alpine OpenRC reads /etc/conf.d/hostname (hostname=...) and/or /etc/hostname
printf '%s\n' "$APP_HOSTNAME" >/etc/hostname
cat >/etc/conf.d/hostname <<EOF
# Managed by Schnapp appliance provision
hostname="${APP_HOSTNAME}"
EOF
# Apply now inside the image build (best-effort)
hostname "$APP_HOSTNAME" 2>/dev/null || true
if command -v setup-hostname >/dev/null 2>&1; then
	setup-hostname "$APP_HOSTNAME" 2>/dev/null || true
	printf '%s\n' "$APP_HOSTNAME" >/etc/hostname
	cat >/etc/conf.d/hostname <<EOF
hostname="${APP_HOSTNAME}"
EOF
fi
# Ensure OpenRC hostname service is on boot (alpine-make-vm-image usually adds it)
rc-update add hostname boot 2>/dev/null || true

einfo "root password (from ROOT_PASSWORD)"
# Prefer shadow utilities when present; fail the build if password is not set.
if ! command -v chpasswd >/dev/null 2>&1; then
	apk add --no-cache shadow 2>/dev/null || apk add shadow || true
fi
if ! printf 'root:%s\n' "$ROOT_PASSWORD" | chpasswd; then
	edie "chpasswd failed — root password not set"
fi
# Sanity: root hash must not be locked/empty
root_hash=$(awk -F: '$1=="root"{print $2}' /etc/shadow 2>/dev/null || true)
case "$root_hash" in
	''|'!'|'*'|'!!') edie "root password still locked/empty after chpasswd (hash='$root_hash')" ;;
	*) einfo "root password hash present (${#root_hash} chars)" ;;
esac

einfo "appliance users"
addgroup -S schnapp 2>/dev/null || true
# Login shell so SSH key auth works for user schnapp; services still use this uid
if ! id schnapp >/dev/null 2>&1; then
	adduser -S -D -h /home/schnapp -s /bin/ash -G schnapp schnapp 2>/dev/null \
		|| adduser -D -h /home/schnapp -s /bin/ash -G schnapp schnapp 2>/dev/null \
		|| true
else
	# Existing image user: ensure home + shell suitable for SSH
	mkdir -p /home/schnapp
	chown schnapp:schnapp /home/schnapp 2>/dev/null || true
	if command -v usermod >/dev/null 2>&1; then
		usermod -d /home/schnapp -s /bin/ash schnapp 2>/dev/null || true
	fi
fi

einfo "static SSH authorized_keys (from build host scripts/appliance/ssh/)"
install_authorized_keys() {
	user="$1"
	home="$2"
	src="$3"
	[ -f "$src" ] || return 0
	# Drop comment-only / empty lines
	if ! grep -vE '^\s*(#|$)' "$src" | grep -q .; then
		ewarn "$src has no key lines — skip $user"
		return 0
	fi
	mkdir -p "${home}/.ssh"
	# Filter comments for the live file but keep a copy of source notes out
	grep -vE '^\s*#' "$src" | grep -vE '^\s*$' >"${home}/.ssh/authorized_keys" || true
	chown -R "${user}:${user}" "${home}/.ssh"
	chmod 700 "${home}/.ssh"
	chmod 600 "${home}/.ssh/authorized_keys"
	einfo "installed SSH keys for ${user} ($(wc -l <"${home}/.ssh/authorized_keys") key line(s))"
}
install_authorized_keys root /root /mnt/ssh/authorized_keys.root
install_authorized_keys schnapp /home/schnapp /mnt/ssh/authorized_keys.schnapp

einfo "static SSH host keys (server identity — avoids known_hosts churn on rebuild)"
if [ -d /mnt/ssh/hostkeys ] && ls /mnt/ssh/hostkeys/ssh_host_*_key >/dev/null 2>&1; then
	# Remove any keys generated by the openssh package install
	rm -f /etc/ssh/ssh_host_* 2>/dev/null || true
	for f in /mnt/ssh/hostkeys/ssh_host_*; do
		[ -f "$f" ] || continue
		base=$(basename "$f")
		cp -a "$f" "/etc/ssh/${base}"
	done
	chmod 600 /etc/ssh/ssh_host_*_key 2>/dev/null || true
	chmod 644 /etc/ssh/ssh_host_*.pub 2>/dev/null || true
	# Prevent sshd first-boot regeneration of missing types if we only ship ed25519+rsa
	if [ -f /etc/conf.d/sshd ]; then
		# Alpine may use sshd service; ensure no forced rekey script wipes us
		:
	fi
	# Drop sshd "generate keys if missing" side effects: mark host keys present
	einfo "installed host keys:"
	for pub in /etc/ssh/ssh_host_*.pub; do
		[ -f "$pub" ] || continue
		ssh-keygen -lf "$pub" 2>/dev/null || true
	done
else
	ewarn "no /mnt/ssh/hostkeys/ssh_host_*_key — sshd will generate new host keys (rebuilds break known_hosts)"
fi

einfo "directories"
# data/ is an empty mountpoint on the system disk until the second volume attaches
mkdir -p /opt/schnapp/api /opt/schnapp/web /opt/schnapp/config \
	"$DATA_MOUNTPOINT" /var/lib/schnapp-appliance /var/log \
	/etc/schnapp /srv/schnapp-clients /var/log/samba

einfo "install published binaries"
if [ ! -d /mnt/publish/api ] || [ ! -d /mnt/publish/web ]; then
	edie "/mnt/publish/{api,web} missing — build-appliance must publish first"
fi
cp -a /mnt/publish/api/. /opt/schnapp/api/
cp -a /mnt/publish/web/. /opt/schnapp/web/
# run.sh wrappers come from overlay; ensure present after publish copy
if [ -f /opt/schnapp/api/run.sh ]; then chmod 755 /opt/schnapp/api/run.sh; fi
if [ -f /opt/schnapp/web/run.sh ]; then chmod 755 /opt/schnapp/web/run.sh; fi
# Overlay may have been applied before publish wiped run.sh — re-install wrappers
if [ ! -f /opt/schnapp/api/run.sh ]; then
	cat >/opt/schnapp/api/run.sh <<'EOS'
#!/bin/sh
set -eu
cd /opt/schnapp/api
if [ -f /opt/schnapp/config/api.env ]; then set -a; . /opt/schnapp/config/api.env; set +a; fi
export ASPNETCORE_ENVIRONMENT="${ASPNETCORE_ENVIRONMENT:-Production}"
if [ -x ./Schnapp.Api ]; then exec ./Schnapp.Api; fi
exec /usr/bin/dotnet ./Schnapp.Api.dll
EOS
	chmod 755 /opt/schnapp/api/run.sh
fi
if [ ! -f /opt/schnapp/web/run.sh ]; then
	cat >/opt/schnapp/web/run.sh <<'EOS'
#!/bin/sh
set -eu
cd /opt/schnapp/web
if [ -f /opt/schnapp/config/web.env ]; then set -a; . /opt/schnapp/config/web.env; set +a; fi
export ASPNETCORE_ENVIRONMENT="${ASPNETCORE_ENVIRONMENT:-Production}"
if [ -x ./Schnapp.Web ]; then exec ./Schnapp.Web; fi
exec /usr/bin/dotnet ./Schnapp.Web.dll
EOS
	chmod 755 /opt/schnapp/web/run.sh
fi
chmod 755 /usr/local/sbin/schnapp-* 2>/dev/null || true
chmod 755 /etc/init.d/schnapp-* 2>/dev/null || true

chown -R schnapp:schnapp /opt/schnapp/api /opt/schnapp/web /opt/schnapp/config
chmod 750 /opt/schnapp/config
# Do not chown data mountpoint to schnapp wholesale — postgres owns PGDATA after mount

# Allow Web (user schnapp) to bind :80 / :443
if [ -x /opt/schnapp/web/Schnapp.Web ] && command -v setcap >/dev/null 2>&1; then
	setcap 'cap_net_bind_service=+ep' /opt/schnapp/web/Schnapp.Web \
		|| ewarn "setcap failed on Schnapp.Web — install libcap-utils"
fi
# Default TLS material (regenerated on first configure/firstboot if missing)
if [ -x /usr/local/sbin/schnapp-ensure-tls ]; then
	/usr/local/sbin/schnapp-ensure-tls --cn "$APP_HOSTNAME" || true
fi

einfo "tray client kits for SMB share"
if [ -d /mnt/clients ]; then
	cp -a /mnt/clients/. /srv/schnapp-clients/
fi
chown -R nobody:nogroup /srv/schnapp-clients 2>/dev/null \
	|| chown -R nobody:nobody /srv/schnapp-clients 2>/dev/null \
	|| true
chmod -R a+rX /srv/schnapp-clients

einfo "write conf.d from build defaults"
cat >/etc/conf.d/schnapp-appliance <<EOF
HOSTNAME="${APP_HOSTNAME}"
SCHNAPP_PREFIX="/opt/schnapp"
DATA_DISK_LABEL="${DATA_DISK_LABEL}"
DATA_MOUNTPOINT="${DATA_MOUNTPOINT}"
PGDATA="${PGDATA}"
BLOB_MOUNTPOINT="${BLOB_MOUNTPOINT}"
BLOB_NFS="${BLOB_NFS}"
BLOB_NFS_OPTS="rw,hard,timeo=100,retrans=2,_netdev"
DB_NAME="${DB_NAME}"
DB_USER="${DB_USER}"
DB_PASSWORD="${DB_PASSWORD}"
API_PORT="${API_PORT}"
WEB_PORT="${WEB_PORT}"
HTTPS_PORT="${HTTPS_PORT}"
HTTPS_ENABLE="${HTTPS_ENABLE}"
API_BIND="${API_BIND}"
WEB_BIND="${WEB_BIND}"
ADMIN_EMAIL="${ADMIN_EMAIL}"
ADMIN_PASSWORD="${ADMIN_PASSWORD}"
BACKUP_DIR="${BACKUP_DIR}"
EOF

einfo "PostgreSQL PGDATA + low-RAM snippet"
# Unversioned cluster on the data volume (OpenRC postgresql / postgresql16)
for pgconf in /etc/conf.d/postgresql /etc/conf.d/postgresql16; do
	cat >"$pgconf" <<EOF
PGDATA="${PGDATA}"
EOF
done
mkdir -p /etc/schnapp
cat >/etc/schnapp/postgresql-appliance.conf <<'EOF'
# Schnapp appliance — low-RAM defaults (include from PGDATA/postgresql.conf or use ALTER SYSTEM)
shared_buffers = 64MB
work_mem = 4MB
maintenance_work_mem = 32MB
effective_cache_size = 256MB
max_connections = 30
listen_addresses = '127.0.0.1'
EOF

einfo "disable IPv6 (sysctl + dhcpcd + kernel cmdline)"
mkdir -p /etc/sysctl.d
# Overlay may already provide 00-schnapp-disable-ipv6.conf; ensure present
if [ ! -f /etc/sysctl.d/00-schnapp-disable-ipv6.conf ]; then
	cat >/etc/sysctl.d/00-schnapp-disable-ipv6.conf <<'EOF'
net.ipv6.conf.all.disable_ipv6 = 1
net.ipv6.conf.default.disable_ipv6 = 1
net.ipv6.conf.lo.disable_ipv6 = 1
EOF
fi
# Kernel: ipv6.disable=1 on next boots (extlinux / update-extlinux)
if [ -f /etc/update-extlinux.conf ]; then
	if grep -q '^default_kernel_opts=' /etc/update-extlinux.conf; then
		if ! grep -q 'ipv6.disable=1' /etc/update-extlinux.conf; then
			sed -i 's|^default_kernel_opts="\(.*\)"|default_kernel_opts="\1 ipv6.disable=1"|' \
				/etc/update-extlinux.conf \
			|| sed -i 's|^default_kernel_opts=\(.*\)|default_kernel_opts=\1 ipv6.disable=1|' \
				/etc/update-extlinux.conf
		fi
	else
		echo 'default_kernel_opts="ipv6.disable=1 quiet"' >>/etc/update-extlinux.conf
	fi
	if command -v update-extlinux >/dev/null 2>&1; then
		update-extlinux --warn-only 2>/dev/null || true
	fi
fi
# sshd: do not listen on IPv6 only issues; AddressFamily inet
if [ -f /etc/ssh/sshd_config ]; then
	if grep -q '^#\?AddressFamily' /etc/ssh/sshd_config; then
		sed -i 's/^#\?AddressFamily.*/AddressFamily inet/' /etc/ssh/sshd_config
	else
		echo 'AddressFamily inet' >>/etc/ssh/sshd_config
	fi
fi

einfo "OpenRC services"
rc-update add networking boot 2>/dev/null || true
rc-update add sshd default 2>/dev/null || true
# sysctl applied at boot via sysctl service (usually in sysinit/boot)
rc-update add sysctl boot 2>/dev/null || rc-update add sysctl sysinit 2>/dev/null || true
# Data volume: sysinit (before postgres) and boot (retry if sysinit oneshot was skipped)
rc-update add schnapp-data-volume sysinit 2>/dev/null || true
rc-update add schnapp-data-volume boot 2>/dev/null || true
rc-update add schnapp-firstboot default 2>/dev/null || true
if [ -f /etc/init.d/postgresql ]; then
	rc-update add postgresql default 2>/dev/null || true
elif [ -f /etc/init.d/postgresql16 ]; then
	rc-update add postgresql16 default 2>/dev/null || true
fi
if [ -f /etc/init.d/samba ]; then
	rc-update add samba default 2>/dev/null || true
elif [ -f /etc/init.d/smbd ]; then
	rc-update add smbd default 2>/dev/null || true
fi
rc-update add schnapp-api default 2>/dev/null || true
rc-update add schnapp-web default 2>/dev/null || true
rc-update add schnapp-issue default 2>/dev/null || true
rc-update add local default 2>/dev/null || true

if [ ! -f /etc/samba/smb.conf ]; then
	ewarn "/etc/samba/smb.conf missing"
fi

if [ -f /etc/ssh/sshd_config ]; then
	sed -i 's/^#\?PermitRootLogin.*/PermitRootLogin yes/' /etc/ssh/sshd_config
	sed -i 's/^#\?PasswordAuthentication.*/PasswordAuthentication yes/' /etc/ssh/sshd_config
	sed -i 's/^#\?PubkeyAuthentication.*/PubkeyAuthentication yes/' /etc/ssh/sshd_config
	# Ensure AuthorizedKeysFile default
	grep -q '^AuthorizedKeysFile' /etc/ssh/sshd_config \
		|| echo 'AuthorizedKeysFile .ssh/authorized_keys' >>/etc/ssh/sshd_config
fi

einfo "disable serial getty (ttyS0) — no reliable serial on QNAP VS"
if [ -f /etc/inittab ]; then
	# Comment any active ttyS0 getty / respawn lines
	sed -i -E \
		-e 's/^([^#].*ttyS0.*)/#\1/' \
		-e 's/^([^#].*getty.*ttyS0.*)/#\1/' \
		/etc/inittab
	# If Alpine uses "ttyS0::respawn:..." form without prior match
	sed -i '/ttyS0/s/^[^#]/#&/' /etc/inittab
fi

einfo "login banners (/etc/issue pre-login, /etc/motd post-login)"
chmod 755 /usr/local/sbin/schnapp-update-issue \
	/etc/local.d/schnapp-issue.start \
	/etc/init.d/schnapp-issue 2>/dev/null || true
# dhcpcd.exit-hook must be executable on some setups; readable is enough for sourcing
chmod 644 /etc/dhcpcd.exit-hook 2>/dev/null || true
if [ -x /usr/local/sbin/schnapp-update-issue ]; then
	/usr/local/sbin/schnapp-update-issue || true
fi

# Final identity check (fail build if hostname file empty)
hn=$(tr -d ' \t\r\n' </etc/hostname 2>/dev/null || true)
[ -n "$hn" ] || edie "/etc/hostname is empty after provision"
einfo "chroot setup done (hostname file='$hn')"
